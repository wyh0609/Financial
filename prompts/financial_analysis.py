# -*- coding: utf-8 -*-
from langchain_core.prompts import PromptTemplate

PROMPT = """你是一位资深的财务分析师。你的任务是从{company}（年份：{year}）的年报原始文本中提取财务指标并评分。

## 重要：数据格式说明

中国年报中的财务数据通常以表格形式呈现，格式如下：
```
项目                    本期金额        上期金额
营业收入              421,296,738.60   339,010,123.47
营业成本              339,010,123.47   253,785,916.92
流动资产合计          523,456,789.00   412,345,678.00
流动负债合计          250,000,000.00   200,000,000.00
存货                  120,000,000.00    98,000,000.00
资产总计              850,000,000.00   700,000,000.00
负债合计              300,000,000.00   250,000,000.00
货币资金              180,000,000.00   150,000,000.00
短期借款              50,000,000.00     30,000,000.00
所有者权益合计       550,000,000.00   450,000,000.00
归属于母公司所有者权益 540,000,000.00   440,000,000.00
```

**关键规则**：
1. 数值通常带逗号分隔千位，如 `421,296,738.60`
2. 第一个数值通常是"本期/本年"，第二个是"上期/上年"
3. 如果一行包含多个数字，取第一个作为当前年份数据
4. "合计"行就是你要用的汇总数据（如"流动资产合计"、"负债合计"）
5. 跳过表头行（如"项目 本期 上期"这种没有实际数字的行）
6. 百分比格式如 `"24.27%"` 直接提取数字部分

需要提取的数据项（按优先级排序）

必须找到的：
1. 营业收入 - 利润表中，找含"营业收入"且有具体金额的行
2. 营业成本 - 利润表中，找含"营业成本"且有具体金额的行
3. 净利润 - 优先找"归属于母公司所有者的净利润"，其次找"净利润"
4. 流动资产合计或 流动资产 - 资产负债表中
5. 流动负债合计 或 流动负债 - 资产负债表中
6. 存货 - 资产负债表中
7. 资产总计 或 总资产 - 资产负债表中
8. 负债合计 或 总负债 - 资产负债表中
9. 所有者权益合计 或 归属于母公司所有者权益合计
10. 货币资金 - 资产负债表中
11. 短期借款 - 资产负债表中（如果找不到，说明无短期借款）
12. **总股本 / 股本总额 / 股份总数** - 资产负债表或附注中（估值计算必需）
13. **基本每股收益** - 利润表末尾或附注中（估值计算必需）

### 可选的：
14. 非经常性损益 - 通常在附注中
15. 支付给职工以及为职工支付的现金- 现金流量表中
16. 员工人数 或 员工总数- 通常在"员工情况"章节
17. **稀释每股收益** - 如有则提取
18. **每股净资产** - 如有则直接提取

计算公式

提取到原始数据后，按以下公式计算：

1. 毛利率 = (营业收入 - 营业成本) / 营业收入 × 100
2. 净利率 = 净利润 / 营业收入 × 100
3. ROE = 归属于母公司净利润 / 所有者权益合计 × 100
4. 流动比率 = 流动资产合计 / 流动负债合计
5. 速动比率 = (流动资产合计 - 存货) / 流动负债合计
6. 资产负债率 = 负债合计 / 资产总计 × 100
7. 货币资金/短期借款 = 货币资金 / 短期借款（无短期借款则填"无短期借款"）
8. 营收增长率 = (本期营收 - 上期营收) / 上期营收 × 100
9. 非经常性损益占净利润比例 = |非经常性损益| / |净利润| × 100（找不到则填"无"）
10. 人均薪酬 = 支付给职工现金 / 员工人数（找不到则填"无数据"）
11. **EPS（每股收益）** = 归属于母公司净利润 / 总股本。如果报表中已有"基本每股收益"则直接使用，否则用此公式计算
12. **BPS（每股净资产）** = 归属于母公司所有者权益 / 总股本。如果报表中已有"每股净资产"则直接使用，否则用此公式计算

## 雷达图评分规则（0-100分，精确到小数点后1位）

基于上述计算出的原始值，请对以下10个指标分别给出0-100分的综合评分。评分要体现该指标在同行业中的相对优劣水平：

1. 流动比率 (current_ratio_score)
- ≥2.0：95-100分（流动性极强）
- 1.5-2.0：80-94分（流动性良好）
- 1.0-1.5：60-79分（流动性一般）
- 0.5-1.0：30-59分（流动性偏弱）
- <0.5：0-29分（流动性风险高）
- 精确插值，例如1.8约88分

2. 速动比率 (quick_ratio_score)
- ≥1.5：95-100分
- 1.0-1.5：75-94分
- 0.5-1.0：50-74分
- 0.2-0.5：20-49分
- <0.2：0-19分

3. 货币资金/短期借款 (cash_short_loan_ratio_score)
- 无短期借款或≥10：100分（完全覆盖）
- 5-10：80-99分（覆盖良好）
- 1-5：40-79分（部分覆盖）
- <1：0-39分（无法覆盖）

4. 资产负债率 (debt_ratio_score) — 越低越好
- ≤30%：90-100分（非常稳健）
- 30%-50%：75-89分（稳健）
- 50%-70%：50-74分（适中偏高）
- 70%-85%：20-49分（杠杆较高）
- >85%：0-19分（高风险）

5. 非经常性损益占比 (non_recurring_profit_ratio_score) — 越低越好
- ≤3%：90-100分（盈利质量极高）
- 3%-10%：75-89分（盈利质量良好）
- 10%-25%：50-74分（有一定依赖）
- 25%-50%：20-49分（高度依赖）
- >50%：0-19分（盈利质量差）

6. 人均薪酬 (per_capita_salary_score) — 年薪(元)
- ≥30万：90-100分（薪酬优厚）
- 15万-30万：70-89分（薪酬较好）
- 5万-15万：40-69分（薪酬一般）
- 2万-5万：15-39分（薪酬偏低）
- <2万：0-14分

7. 毛利率 (gross_margin_score)
- ≥50%：90-100分（高毛利行业龙头）
- 30%-50%：70-89分（毛利良好）
- 15%-30%：45-69分（毛利一般）
- 5%-15%：15-44分（毛利较低）
- <5%或负数：0-14分

8. 净利率 (net_margin_score)
- ≥20%：90-100分（盈利能力极强）
- 10%-20%：70-89分（盈利能力强）
- 3%-10%：45-69分（盈利能力一般）
- 0%-3%：15-44分（微利）
- <0%（亏损）：0-14分

9. ROE (roe_score)
- ≥20%：90-100分（股东回报极高）
- 10%-20%：70-89分（股东回报良好）
- 3%-10%：45-69分（股东回报一般）
- 0%-3%：15-44分（微弱回报）
- <0%（亏损）：0-14分

10. 营收增长率 (revenue_growth_score)
- ≥30%：90-100分（高速增长）
- 15%-30%：75-89分（快速增长）
- 5%-15%：55-74分（稳步增长）
- 0%-5%：35-54分（缓慢增长）
- -10%~0%：15-34分（轻微下滑）
- <-10%：0-14分（大幅下滑）

输出格式

严格输出JSON，不要任何其他文字。radar_scores中每项必须是0-100之间的数字，精确到小数点后1位：

{{"current_ratio": 数字或null, "quick_ratio": 数字或null, "cash_short_loan_ratio": 数字或"无短期借款"或null, "debt_ratio": 数字或null, "gross_margin": 数字或null, "net_margin": 数字或null, "roe": 数字或null, "revenue_growth": 数字或null, "non_recurring_profit_ratio": 数字或"无"或null, "per_capita_salary": 数字或"无数据"或null, "net_profit_trend": [历年净利润列表，单位万元], "eps": 数字或null, "bps": 数字或null, "total_shares": 数字或null, "radar_scores": {{"流动比率": 0-100分数, "速动比率": 0-100分数, "货币资金/短期借款": 0-100分数, "资产负债率": 0-100分数, "非经常性损益占比": 0-100分数, "人均薪酬": 0-100分数, "毛利率": 0-100分数, "净利率": 0-100分数, "ROE": 0-100分数, "营收增长率": 0-100分数}}, "raw_data_summary": {{"revenue": "值和来源", "cost": "值和来源", "profit": "值和来源", "current_assets": "值和来源", "current_liabilities": "值和来源", "inventory": "值和来源", "total_shares": "值和来源", "eps": "值和来源", "owner_equity": "值和来源"}}}}

## 原始财报文本

{context}

请仔细阅读以上文本，逐行查找每个数据项，计算原始指标值，然后根据评分规则给出每个指标的0-100评分，最后输出JSON：
"""

def financial_analysis_prompt(company="该公司", year="", context=""):
    return PromptTemplate(template=PROMPT, input_variables=["company", "year", "context"])
    
if __name__ == "__main__":
    print(financial_analysis_prompt().format(company="安记食品", year="2019", context="测试上下文"))
